dofile(reaper.GetResourcePath() .. "/Scripts/harness.lua")
local vox = harness.track("Vox")
reaper.TrackFX_AddByName(vox, "JS:synthesis/tonegenerator", false, -1)
reaper.TrackFX_AddByName(vox, "JS:utility/volume", false, -1)
local verb = harness.track("Verb")
